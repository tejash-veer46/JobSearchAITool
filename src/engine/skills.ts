/** Automation tools; used to tell automation roles from manual-only ones. */
export const AUTOMATION_SKILLS = new Set([
  'Playwright', 'Selenium', 'Cypress', 'Appium', 'WebdriverIO', 'TestNG', 'JUnit', 'Cucumber/BDD',
  'REST Assured', 'Robot Framework', 'Pytest', 'Karate',
]);

export function findSkills(text: string): string[] {
  return SKILLS.filter(([, re]) => re.test(text)).map(([name]) => name);
}
